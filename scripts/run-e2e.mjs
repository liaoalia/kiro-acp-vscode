#!/usr/bin/env node
/**
 * Launch the extension-host integration tests inside a real VS Code.
 *
 * This script builds nothing: `npm run test:e2e` runs `npm run build` (dist/)
 * and `npm run compile-e2e` (out/e2e/) first. What it does:
 *
 *   1. Creates a throw-away workspace folder in the OS temp directory with a
 *      README.md, src/sample.ts and a .vscode/settings.json that points
 *      `kiroAcp.cliPath` / `kiroAcp.cliArgs` at the fake ACP agent
 *      (test/fake-agent) started with `--scenario tour`.
 *   2. Downloads VS Code "stable" into .vscode-test/ on first run (~120 MB)
 *      and launches it with this repo as the development extension and
 *      out/e2e/test/e2e/index.js as the test entry point.
 *   3. Exits with the test result (0 = all passed).
 *
 * On Windows `cliPath` is the `kiro-cli-fake.cmd` wrapper: the extension's
 * process layer routes `.cmd`/`.bat` executables through cmd.exe itself
 * (Node refuses to spawn them without a shell, CVE-2024-27980), so the test
 * exercises the same code path a user with a .cmd wrapper would hit.
 */
import { runTests } from "@vscode/test-electron";
import { chmodSync, existsSync, mkdirSync, mkdtempSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const fakeAgentDir = path.join(repo, "test", "fake-agent");
const testsEntry = path.join(repo, "out", "e2e", "test", "e2e", "index.js");

if (!existsSync(testsEntry)) {
  console.error(`Missing ${testsEntry} — run \`npm run compile-e2e\` (or \`npm run test:e2e\`) first.`);
  process.exit(2);
}
if (!existsSync(path.join(repo, "dist", "extension.js"))) {
  console.error("Missing dist/extension.js — run `npm run build` (or `npm run test:e2e`) first.");
  process.exit(2);
}

// A stale bundle silently tests old code: warn when any source is newer than dist/.
{
  const distMtime = statSync(path.join(repo, "dist", "extension.js")).mtimeMs;
  const newer = [];
  const walk = (dir) => {
    for (const name of readdirSync(dir)) {
      const full = path.join(dir, name);
      const st = statSync(full);
      if (st.isDirectory()) walk(full);
      else if (st.mtimeMs > distMtime) newer.push(path.relative(repo, full));
    }
  };
  walk(path.join(repo, "src"));
  if (newer.length > 0) {
    console.error(
      `[e2e] WARNING: dist/extension.js is older than ${newer.length} source file(s) (e.g. ${newer[0]}); run npm run build first.`,
    );
  }
}

function cliSettings() {
  if (process.platform === "win32") {
    return {
      "kiroAcp.cliPath": path.join(fakeAgentDir, "kiro-cli-fake.cmd"),
      "kiroAcp.cliArgs": ["--scenario", "tour"],
    };
  }
  const wrapper = path.join(fakeAgentDir, "kiro-cli-fake");
  try {
    chmodSync(wrapper, 0o755);
  } catch {
    // best effort; the checked-in file is already executable
  }
  return { "kiroAcp.cliPath": wrapper, "kiroAcp.cliArgs": ["--scenario", "tour"] };
}

const SAMPLE_TS = `/** Sample module used by the Kiro ACP integration tests. */
export interface Greeting {
  name: string;
  excited: boolean;
}

export function greet(input: Greeting): string {
  const suffix = input.excited ? "!" : ".";
  return \`Hello, \${input.name}\${suffix}\`;
}

export function shout(text: string): string {
  return text.toUpperCase();
}

export function whisper(text: string): string {
  return text.toLowerCase();
}

export const DEFAULT_GREETING: Greeting = { name: "world", excited: false };
`;

const README = `# Kiro ACP e2e workspace

This folder is generated by scripts/run-e2e.mjs for one test run.

- The fake agent reads this file through fs/read_text_file.
- src/sample.ts is used for selection and @file context chips.
`;

const tmpRoot = mkdtempSync(path.join(tmpdir(), "kiro-e2e-"));
const workspace = path.join(tmpRoot, "workspace");
const userDataDir = path.join(tmpRoot, "user-data");
mkdirSync(path.join(workspace, "src"), { recursive: true });
mkdirSync(path.join(workspace, ".vscode"), { recursive: true });
mkdirSync(userDataDir, { recursive: true });
writeFileSync(path.join(workspace, "README.md"), README);
writeFileSync(path.join(workspace, "src", "sample.ts"), SAMPLE_TS);
writeFileSync(
  path.join(workspace, ".vscode", "settings.json"),
  JSON.stringify(
    {
      ...cliSettings(),
      // The default: proposal diffs open from the permission path (syncPermissions);
      // tests that need `always` / `never` set it themselves and restore it.
      "kiroAcp.autoOpenDiffs": "whenPermissionRequired",
      "kiroAcp.attachActiveFile": true,
      "files.autoSave": "off",
      "workbench.startupEditor": "none",
      "extensions.ignoreRecommendations": true,
      "telemetry.telemetryLevel": "off",
      "update.mode": "none",
    },
    null,
    2,
  ),
);

console.log(`[e2e] workspace: ${workspace}`);

let exitCode = 1;
try {
  await runTests({
    version: "stable",
    extensionDevelopmentPath: repo,
    extensionTestsPath: testsEntry,
    launchArgs: [
      workspace,
      "--disable-extensions",
      "--disable-workspace-trust",
      `--user-data-dir=${userDataDir}`,
    ],
    extensionTestsEnv: { KIRO_E2E_WORKSPACE: workspace },
  });
  exitCode = 0;
} catch (error) {
  console.error(`[e2e] failed: ${error instanceof Error ? error.message : String(error)}`);
  exitCode = 1;
} finally {
  try {
    rmSync(tmpRoot, { recursive: true, force: true, maxRetries: 5, retryDelay: 200 });
  } catch (error) {
    console.warn(`[e2e] could not remove ${tmpRoot}: ${error instanceof Error ? error.message : String(error)}`);
  }
}
process.exit(exitCode);
